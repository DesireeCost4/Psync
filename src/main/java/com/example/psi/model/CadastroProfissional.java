package com.example.psi.model;

public class CadastroProfissional {

    private String nome;
    private String razaoSocial;
    private String email;
    private String telefone;
    private String documento;
    private String seguimentoTipo;
    private String password;

    public String getNome() { return nome; }
    public void setNome(String nome) { this.nome = nome; }
    public String getRazaoSocial() { return razaoSocial; }
    public void setRazaoSocial(String razaoSocial) { this.razaoSocial = razaoSocial; }
    public String getEmail() { return email; }
    public void setEmail(String email) { this.email = email; }
    public String getTelefone() { return telefone; }
    public void setTelefone(String telefone) { this.telefone = telefone; }
    public String getDocumento() { return documento; }
    public void setDocumento(String documento) { this.documento = documento; }
    public String getSeguimentoTipo() { return seguimentoTipo; }
    public void setSeguimentoTipo(String seguimentoTipo) { this.seguimentoTipo = seguimentoTipo; }
    public String getPassword() { return password; }
    public void setPassword(String password) { this.password = password; }
}
